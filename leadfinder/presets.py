def resolve(names: list[str]) -> list[str]:
    """Разворачивает имена пресетов в запросы. Неизвестное имя считаем запросом."""
    queries: list[str] = []
    for name in names:
        key = name.strip().casefold()
        if key in PRESETS:
            queries.extend(PRESETS[key])
        else:
            queries.append(name.strip())

    # Убираем дубли, сохраняя порядок
    seen: set[str] = set()
    unique: list[str] = []
    for query in queries:
        if query and query.casefold() not in seen:
            seen.add(query.casefold())
            unique.append(query)
    return unique
