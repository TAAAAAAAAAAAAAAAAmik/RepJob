"""Площадки, на которых у компании есть рейтинг.

Цифры на разных площадках расходятся, и заметно: кафе с 3.1 в 2ГИС
спокойно бывает 4.4 в Яндексе — там другие отзывы, другие люди и другая
формула. Поэтому «у вас низкий рейтинг» без названия площадки — это
проигранный разговор: владелец откроет вторую карту и закроет тему.

Отсюда выбор источника перед поиском. Модуль намеренно ничего не
импортирует из проекта: это справочник, а не логика.
"""

from __future__ import annotations

from dataclasses import dataclass

# Ключ источника по умолчанию: то, что человек видит, открыв карточку точки.
DEFAULT = "2gis"


@dataclass(frozen=True)
class Source:
    """Одна площадка (или охват внутри площадки) как источник рейтинга."""

    key: str
    title: str        # подпись кнопки — коротко, влезает в ряд
    caption: str      # как назвать в шапке выдачи
    note: str         # чем этот рейтинг отличается от соседнего
    available: bool = True
    why_not: str = ""  # если поиск по нему невозможен — почему


TWO_GIS = Source(
    key="2gis",
    title="📍 2ГИС — карточка филиала",
    caption="2ГИС, филиал",
    note="оценка одной точки по отзывам 2ГИС. Её и видит человек, открывший карточку",
)

TWO_GIS_ORG = Source(
    key="2gis_org",
    title="🏢 2ГИС — вся организация",
    caption="2ГИС, организация",
    note="все филиалы вместе плюс Flamp. У сетей расходится с филиальной на полбалла",
)

YANDEX = Source(
    key="yandex",
    title="🔵 Яндекс.Карты",
    caption="Яндекс",
    note="на карте рейтинг есть, в API его нет. Искать по нему нельзя",
    available=False,
    why_not=(
        "У Яндекса рейтинга нет в API. «Поиск по организациям» отдаёт "
        "название, адрес, телефон, часы и рубрики — и всё: полей с оценкой "
        "и числом отзывов в ответе просто не существует. Отбирать «3.0–4.2» "
        "там нечем.\n\n"
        "Что с этим делать:\n"
        "• Ищем по 2ГИС — рейтинг берётся оттуда.\n"
        "• У каждого лида уже стоит ссылка на Яндекс: тап — и оценка видна "
        "глазами. Расхождение между площадками само по себе сильный "
        "аргумент в разговоре.\n"
        "• Телефоны Яндекс отдаёт: с ключом они подставляются сами."
    ),
)

SOURCES: dict[str, Source] = {s.key: s for s in (TWO_GIS, TWO_GIS_ORG, YANDEX)}


def get(key: str) -> Source:
    """Источник по ключу. Неизвестный ключ — источник по умолчанию.

    Ключ приезжает из callback_data, то есть снаружи: старая кнопка из
    прошлой версии бота не должна ронять поиск.
    """
    return SOURCES.get(key) or SOURCES[DEFAULT]


def title_of(key: str) -> str:
    """Как назвать источник в выдаче и в CSV."""
    return get(key).caption


def searchable() -> list[Source]:
    """Источники, по которым реально можно отобрать компании."""
    return [s for s in SOURCES.values() if s.available]
